package postgres

import (
	"crypto/aes"
	"crypto/cipher"
	"crypto/rand"
	"crypto/sha256"
	"errors"
	"fmt"
)

// runtimeKeyVersion tags ciphertexts with the server key that sealed them.
// shortcut: only one version exists; rotating PERSONAL_AI_RUNTIME_KEY_SECRET
// needs a second keyCipher and a re-encryption pass before the old one goes.
const runtimeKeyVersion = 1

// keyCipher encrypts runtime keys at rest (ADR 0009): AES-256-GCM with a
// random nonce and the deployment ID as associated data, so a ciphertext
// copied onto another row does not decrypt.
type keyCipher struct{ aead cipher.AEAD }

func newKeyCipher(secret string) (keyCipher, error) {
	if len(secret) < 24 {
		return keyCipher{}, errors.New("runtime key secret must be at least 24 characters")
	}
	// The secret is long and random (generated by make k8s-secrets), so a hash
	// is enough to shape it into an AES key; the label separates its uses.
	k := sha256.Sum256([]byte("personal-ai runtime-key v1\x00" + secret))
	block, err := aes.NewCipher(k[:])
	if err != nil {
		return keyCipher{}, err
	}
	aead, err := cipher.NewGCM(block)
	if err != nil {
		return keyCipher{}, err
	}
	return keyCipher{aead: aead}, nil
}

func (c keyCipher) seal(deploymentID, key string) []byte {
	nonce := make([]byte, c.aead.NonceSize(), c.aead.NonceSize()+len(key)+c.aead.Overhead())
	_, _ = rand.Read(nonce) // crypto/rand.Read never returns an error
	return c.aead.Seal(nonce, nonce, []byte(key), []byte(deploymentID))
}

func (c keyCipher) open(deploymentID string, ciphertext []byte) (string, error) {
	n := c.aead.NonceSize()
	if len(ciphertext) < n {
		return "", errors.New("runtime key ciphertext too short")
	}
	plain, err := c.aead.Open(nil, ciphertext[:n], ciphertext[n:], []byte(deploymentID))
	if err != nil {
		return "", fmt.Errorf("decrypt runtime key: %w", err)
	}
	return string(plain), nil
}
